/*
  좌표는 손으로 찍은 모식도다. landmarks는 그 위에서 잡은 기준점이고, 실측
  트레이싱으로 교체할 때 이 4점을 맞춰 정합한다. (SPEC "저작 도구" 참조)

  OUTLINE만 예외로 **폭 보정**이 들어가 있다. 모양은 원래 손으로 그린 것 그대로고,
  x좌표만 행마다 [원래 좌우 가장자리] → [원래와 Gray443 실루엣의 합집합]으로
  선형 대응시켰다. 뷰 y 275~600 구간에만 적용하고 경계에서는 부드럽게 원본으로
  돌아간다.

  합집합이라 절대 좁아지지 않는다. 도판 뒤꿈치는 지방패드가 제거된 종골이라
  실제보다 좁게 나오므로 그쪽으로 끌려가면 안 되기 때문이다 — 같은 이유로
  윤곽 전체를 도판에서 다시 뜨는 방법은 실패했다(refs/README.md 참조).

  보정한 이유: 모식도 윤곽이 중족부에서 좁고 17단위쯤 내측으로 치우쳐 있어,
  발 가장자리를 따라 달리는 근육을 도판대로 옮기면 밖으로 나갔다. 보정 후
  소지외전근 최대 이탈 33 → 5, 단소지굴근 27 → 4.

  단서: Gray443은 해부 표본이라 조직이 벌어져 실제 발보다 넓게 그려졌을 수 있다.
  그렇다면 이 보정은 다소 과하다. 그래서 traced가 아니라 여전히 schematic이다 —
  측정으로 치수를 고친 모식도이지 실측 윤곽이 아니다.
*/

